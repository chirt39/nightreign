export function abilityGroupNames(kind, entry) {
  const id = Number(entry?.id);
  return Object.entries(groups[kind] || {})
    .filter(([, ids]) => ids.includes(id))
    .map(([label]) => label);
}

export function abilityGroupNote(kind, entry) {
  return notes[kind]?.[entry?.id] || '';
}
